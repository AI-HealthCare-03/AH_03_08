  if (/오구멘틴|클래리시드|지트로막스|시프로|팩티브|아목클란|크라목스|클라시드|지트로맥스|아벨록스|타리비드|오라세프|유한세파클러/.test(n)) return '항생제'
  // ── 항바이러스제 ──────────────────────────────────────────────────────────────
  if (/발라시클로버|아시클로버|팜시클로버|오셀타미비르|발간시클로버|엔테카비르/.test(n)) return '항바이러스제'
  if (/발트렉스|조비락스|팜비르|타미플루|바라크루드|헤르페신/.test(n)) return '항바이러스제'
  // ── 항진균제 ──────────────────────────────────────────────────────────────────
  if (/플루코나졸|이트라코나졸|테르비나핀|클로트리마졸|미코나졸/.test(n)) return '항진균제'
  if (/디플루칸|라미실|카네스텐|스포라녹스/.test(n)) return '항진균제'
  // ── 고지혈증 치료제 ───────────────────────────────────────────────────────────
  if (/로수바스타틴|아토르바스타틴|심바스타틴|프라바스타틴|피타바스타틴|플루바스타틴|에제티미브/.test(n)) return '고지혈증 치료제'
  if (/크레스토|리피토|조코|리바로|바이토린|제티아|로수젯/.test(n)) return '고지혈증 치료제'
  // ── 당뇨병 치료제 ─────────────────────────────────────────────────────────────
  if (/메트포르민|글리메피리드|글리피지드|시타글립틴|다파글리플로진|엠파글리플로진|리나글립틴|빌다글립틴|삭사글립틴/.test(n)) return '당뇨병 치료제'
  if (/글루코파지|아마릴|자누비아|포시가|자디앙|가브스|온글라이자/.test(n)) return '당뇨병 치료제'
  // ── 위산억제제 ────────────────────────────────────────────────────────────────
  if (/오메프라졸|에소메프라졸|란소프라졸|판토프라졸|라베프라졸|테고프라잔|보노프라잔/.test(n)) return '위산억제제'
  if (/넥시움|란스톤|판토록|파리에트|케이캡|타케캡/.test(n)) return '위산억제제'
  // ── 위점막 보호제 ─────────────────────────────────────────────────────────────
  if (/레바미피드|무코스타|수크랄페이트|비스무트|알긴산/.test(n)) return '위점막 보호제'
  // ── 위장운동 촉진제 ───────────────────────────────────────────────────────────
  if (/돔페리돈|메토클로프라미드|이토프리드|모사프리드/.test(n)) return '위장운동 촉진제'
  if (/모티리움|가나톤|스티렌|가스모틴|멕소롱/.test(n)) return '위장운동 촉진제'
  // ── 소화제 ────────────────────────────────────────────────────────────────────
  if (/판크레아틴|소화효소|디아스타제/.test(n)) return '소화제'
  if (/훼스탈|베아제|소화잘되는베아제|닥터베아제/.test(n)) return '소화제'
  // ── 항혈전제 ──────────────────────────────────────────────────────────────────
  if (/클로피도그렐|아스피린|리바록사반|아픽사반|다비가트란|티카그렐러/.test(n)) return '항혈전제'
  if (/플라빅스|자렐토|엘리퀴스|프라닥사|브릴린타/.test(n)) return '항혈전제'
  // ── 고혈압 치료제 ─────────────────────────────────────────────────────────────
  if (/암로디핀|발사르탄|로사르탄|텔미사르탄|칸데사르탄|이르베사르탄|올메사르탄|페린도프릴|에날라프릴|리시노프릴/.test(n)) return '고혈압 치료제'
  if (/노바스크|코자|디오반|미카르디스|아타칸|아카르보스|코아프로벨/.test(n)) return '고혈압 치료제'
  // ── 베타차단제 ────────────────────────────────────────────────────────────────
  if (/메토프롤롤|카르베딜롤|아테놀롤|비소프롤롤|네비볼롤/.test(n)) return '베타차단제'
  if (/세로켈|코레그|테노민|콩코르|바이소프롤롤/.test(n)) return '베타차단제'
  // ── 이뇨제 ────────────────────────────────────────────────────────────────────
  if (/히드로클로로티아지드|푸로세미드|인다파미드|스피로노락톤/.test(n)) return '이뇨제'
  // ── 갑상선 치료제 ─────────────────────────────────────────────────────────────
  if (/레보티록신|메티마졸|프로필티오우라실/.test(n)) return '갑상선 치료제'
  if (/씬지로이드|신지로이드|안티로이드/.test(n)) return '갑상선 치료제'
  // ── 항히스타민제 ──────────────────────────────────────────────────────────────
  if (/세티리진|로라타딘|펙소페나딘|레보세티리진|빌라스틴|데슬로라타딘|클로르페니라민|아크리바스틴/.test(n)) return '항히스타민제'
  if (/지르텍|클라리틴|알레그라|씨잘|빌라논|코리투사|폴라리스/.test(n)) return '항히스타민제'
  // ── 항알레르기제 ──────────────────────────────────────────────────────────────
  if (/몬테루카스트|자피를루카스트/.test(n)) return '항알레르기제'
  if (/싱귤레어|아콜레이트/.test(n)) return '항알레르기제'
  // ── 기관지확장제 ──────────────────────────────────────────────────────────────
  if (/살부타몰|살메테롤|포르모테롤|티오트로피움|인다카테롤|글리코피로늄/.test(n)) return '기관지확장제'
  if (/벤톨린|세레타이드|스피리바|포스터|심비코트/.test(n)) return '기관지확장제'
  // ── 부신피질호르몬제 ──────────────────────────────────────────────────────────
  if (/프레드니솔론|덱사메타손|메틸프레드니솔론|트리암시놀론/.test(n)) return '부신피질호르몬제'
  if (/메드롤|솔루메드롤|솔루코텝/.test(n)) return '부신피질호르몬제'
  // ── 항우울제 ──────────────────────────────────────────────────────────────────
  if (/세르트랄린|플루옥세틴|에스시탈로프람|시탈로프람|파록세틴|벤라팍신|둘록세틴|미르타자핀/.test(n)) return '항우울제'
  if (/졸로푸트|프로작|렉사프로|팍실|이펙사|심발타|레메론/.test(n)) return '항우울제'
  // ── 항불안제 ──────────────────────────────────────────────────────────────────
  if (/알프라졸람|디아제팜|로라제팜|클로나제팜|부스피론/.test(n)) return '항불안제'
  if (/자낙스|발륨|아티반|리보트릴|부스파/.test(n)) return '항불안제'
  // ── 수면제 ────────────────────────────────────────────────────────────────────
  if (/졸피뎀|트리아졸람|에스조피클론|수보렉산트/.test(n)) return '수면제'
  if (/스틸녹스|할시온|벨솜라/.test(n)) return '수면제'
  // ── 신경통 치료제 ─────────────────────────────────────────────────────────────
