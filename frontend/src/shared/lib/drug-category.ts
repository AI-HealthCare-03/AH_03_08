  // ── 해열진통제 ────────────────────────────────────────────────────────────────
  if (/아세트아미노펜|파라세타몰/.test(n)) return '해열진통제'
  if (/타이레놀|세토펜|판피린|서스펜|써스펜/.test(n)) return '해열진통제'
  // ── 항생제 ────────────────────────────────────────────────────────────────────
